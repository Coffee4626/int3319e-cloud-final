"""Shared contracts; no AWS or ML imports."""
from dataclasses import dataclass
from pathlib import Path
from typing import Optional, Protocol


class NotFoundError(Exception):
    pass


class ConflictError(Exception):
    pass


class UnauthorizedError(Exception):
    pass


@dataclass(frozen=True)
class TrainingRequest:
    csv: str
    target: str
    task: str = "tabular"
    time_limit: int = 60

    @classmethod
    def parse(cls, data: dict):
        request = cls(csv=data.get("csv"), target=data.get("target"),
                      task=data.get("task", "tabular"), time_limit=data.get("time_limit", 60))
        if not isinstance(request.csv, str) or not isinstance(request.target, str) or not request.target:
            raise ValueError("csv and target must be non-empty strings")
        if len(request.csv.encode()) > 10_000_000:
            raise ValueError("CSV limit: 10 MB")
        if type(request.time_limit) is not int or not 10 <= request.time_limit <= 600:
            raise ValueError("time_limit must be an integer from 10 to 600 seconds")
        return request


@dataclass(frozen=True)
class QueueMessage:
    job_id: str
    receipt: str


class JobRepository(Protocol):
    def get_record(self, record_id: str) -> Optional[dict]: ...
    def put_record(self, item: dict, create: bool = False) -> None: ...
    def list_records(self, kind: str, owner: str = "local", cursor: Optional[str] = None) -> dict: ...
    def get_job(self, job_id: str) -> Optional[dict]: ...
    def create_job(self, job: dict) -> None: ...
    def submission_failed(self, job_id: str) -> None: ...
    def claim(self, job_id: str, owner: str, now: int) -> bool: ...
    def heartbeat(self, job_id: str, owner: str) -> bool: ...
    def cancel(self, job_id: str) -> bool: ...
    def dead_letter(self, job_id: str) -> bool: ...
    def finish(self, job_id: str, owner: str, *, model_key: Optional[str] = None,
               error: Optional[str] = None, metrics: Optional[dict] = None) -> bool: ...
    def get_deployment(self, deployment_id: str) -> Optional[dict]: ...
    def create_deployment(self, deployment: dict) -> None: ...
    def update_deployment(self, deployment_id: str, owner: str, fields: dict) -> bool: ...


class ArtifactStore(Protocol):
    def save_csv(self, key: str, csv: str) -> None: ...
    def read_csv(self, key: str, limit: int) -> str: ...
    def presign_upload(self, key: str, limit: int) -> dict: ...
    def download(self, key: str, path: Path) -> None: ...
    def upload_model(self, key: str, directory: Path) -> None: ...
    def extract_model(self, key: str, directory: Path) -> None: ...


class JobQueue(Protocol):
    def enqueue(self, job_id: str) -> None: ...
    def receive(self) -> list[QueueMessage]: ...
    def acknowledge(self, message: QueueMessage) -> None: ...
    def heartbeat(self, message: QueueMessage) -> None: ...
